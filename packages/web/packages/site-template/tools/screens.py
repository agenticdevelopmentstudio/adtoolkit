#!/usr/bin/env python3
"""Screenshot a running site at two viewports, at rest and after scrolling one window.

Run: python3 tools/screens.py --url http://localhost:3000 --out DIR [--route / --route /about]

For each route: 1280x800 and 390x844, each at rest and scrolled down one window height, written
as `<route-slug>-<w>x<h>-{rest,scrolled}.png`. Stdlib-only Python: the browser is driven by a small
Node script, written to a temp dir and run with `npx --yes -p playwright@1.58.2 node ...`, so
there is no Python Playwright dependency.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

PLAYWRIGHT = "playwright@1.58.2"
VIEWPORTS = [(1280, 800), (390, 844)]
STATES = ["rest", "scrolled"]

# npx puts its cache's node_modules/.bin on PATH; the script resolves playwright from there,
# because it lives in a temp dir with no node_modules of its own.
NODE_SCRIPT = """\
// Generated by site-template/tools/screens.py. argv[2] is the job file.
const path = require('path');
const bins = (process.env.PATH || '').split(path.delimiter).filter((p) => p.endsWith(path.join('node_modules', '.bin')));
const { chromium } = require(require.resolve('playwright', { paths: bins.map((p) => path.dirname(p)) }));
const job = JSON.parse(require('fs').readFileSync(process.argv[2], 'utf8'));
(async () => {
  const browser = await chromium.launch();
  try {
    const pages = new Map();
    for (const shot of job.shots) {
      const key = shot.route + '|' + shot.width + 'x' + shot.height;
      let page = pages.get(key);
      if (!page) {
        page = await browser.newPage({ viewport: { width: shot.width, height: shot.height } });
        // 'load', not 'networkidle': next dev keeps its HMR connection open, so the network never idles.
        await page.goto(job.base + shot.route, { waitUntil: 'load' });
        await page.waitForTimeout(500);
        pages.set(key, page);
      }
      if (shot.state === 'scrolled') {
        await page.evaluate(() => window.scrollBy(0, window.innerHeight));
        await page.waitForTimeout(800);
      }
      await page.screenshot({ path: shot.path });
    }
  } finally {
    await browser.close();
  }
})().catch((error) => { console.error(error); process.exit(1); });
"""


@dataclass(frozen=True)
class Capture:
    route: str
    width: int
    height: int
    state: str
    path: Path

    @property
    def name(self) -> str:
        return self.path.name


def route_slug(route: str) -> str:
    slug = re.sub(r"[^A-Za-z0-9]+", "-", route).strip("-")
    # `index`, not `home`: a site with a `/home` route would overwrite `/`'s shots with its own.
    return slug or "index"


def shot_name(route: str, width: int, height: int, state: str) -> str:
    return f"{route_slug(route)}-{width}x{height}-{state}.png"


def plan_captures(routes: list[str], out: Path) -> list[Capture]:
    """Every capture, in order: per route, per viewport, rest then scrolled."""
    return [
        Capture(route, w, h, state, out / shot_name(route, w, h, state))
        for route in routes
        for (w, h) in VIEWPORTS
        for state in STATES
    ]


def node_script() -> str:
    return NODE_SCRIPT


def job_json(base: str, captures: list[Capture]) -> str:
    return json.dumps(
        {
            "base": base.rstrip("/"),
            "shots": [
                {"route": c.route, "width": c.width, "height": c.height, "state": c.state, "path": str(c.path)}
                for c in captures
            ],
        }
    )


def install_argv() -> list[str]:
    return ["npx", "--yes", "-p", PLAYWRIGHT, "playwright", "install", "chromium"]


def node_argv(script: Path, job: Path) -> list[str]:
    return ["npx", "--yes", "-p", PLAYWRIGHT, "node", str(script), str(job)]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Screenshot a running site at two viewports.")
    parser.add_argument("--url", required=True, help="the site's base URL, e.g. http://localhost:3000")
    parser.add_argument("--out", required=True, type=Path, help="the directory the PNGs are written to")
    parser.add_argument("--route", action="append", help="a route to shoot; repeatable; default /")
    args = parser.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)
    captures = plan_captures(args.route or ["/"], args.out.resolve())
    with tempfile.TemporaryDirectory() as tmp:
        script, job = Path(tmp) / "screens.cjs", Path(tmp) / "job.json"
        script.write_text(node_script())
        job.write_text(job_json(args.url, captures))
        try:
            subprocess.run(install_argv(), check=True)
            code = subprocess.run(node_argv(script, job), check=False).returncode
        except FileNotFoundError as error:
            print(f"screens: cannot run {error.filename}: is it installed?", file=sys.stderr)
            return 2
        except subprocess.CalledProcessError as error:
            print(f"screens: {' '.join(error.cmd)} exited {error.returncode}", file=sys.stderr)
            return 2
    if code == 0:
        for capture in captures:
            print(capture.path)
    return code


if __name__ == "__main__":
    sys.exit(main())
